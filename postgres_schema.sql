-- Only initialize_schema() may apply this migration to a fresh namespace.
-- The runtime connection never runs DDL or creates an empty replacement.
CREATE SCHEMA guest_registry;
REVOKE ALL ON SCHEMA guest_registry FROM PUBLIC;

CREATE TABLE guest_registry.registry_meta (
    singleton integer PRIMARY KEY CHECK (singleton = 1),
    schema_version integer NOT NULL CHECK (schema_version = 1),
    registry_id text NOT NULL CHECK (length(registry_id) BETWEEN 1 AND 200),
    admin_id bigint NOT NULL CHECK (admin_id BETWEEN 1 AND 9007199254740991),
    access_seeded boolean NOT NULL DEFAULT false
);
CREATE TABLE guest_registry.guests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    name_key text NOT NULL,
    phone text NOT NULL,
    phone_key text NOT NULL CONSTRAINT guests_phone_key_key UNIQUE,
    comment text NOT NULL CHECK (length(comment) <= 3000),
    photo bytea NOT NULL CHECK (octet_length(photo) <= 10485760),
    photo_file_id text NOT NULL CHECK (length(photo_file_id) <= 1024),
    created_by bigint NOT NULL CHECK (created_by > 0),
    updated_by bigint NOT NULL CHECK (updated_by > 0),
    created_at text NOT NULL,
    updated_at text NOT NULL,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    entry_status text NOT NULL DEFAULT 'open' CHECK (entry_status IN ('open', 'closed')),
    entry_reason text NOT NULL DEFAULT '' CHECK (length(entry_reason) <= 3000),
    CHECK ((octet_length(photo) = 0) = (photo_file_id = ''))
);
CREATE TABLE guest_registry.visits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id bigint NOT NULL REFERENCES guest_registry.guests(id) ON DELETE CASCADE,
    started_at text NOT NULL,
    stopped_at text,
    started_by bigint NOT NULL CHECK (started_by > 0),
    stopped_by bigint CHECK (stopped_by > 0),
    CHECK ((stopped_at IS NULL) = (stopped_by IS NULL)),
    CHECK (stopped_at IS NULL OR stopped_at::timestamptz >= started_at::timestamptz)
);
CREATE UNIQUE INDEX visits_one_active_per_guest ON guest_registry.visits(guest_id)
    WHERE stopped_at IS NULL;
CREATE INDEX visits_guest_started ON guest_registry.visits(guest_id, id DESC);
CREATE TABLE guest_registry.audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id bigint NOT NULL CHECK (guest_id > 0),
    guest_name text NOT NULL,
    actor_id bigint CHECK (actor_id > 0),
    action text NOT NULL CHECK (action IN ('add', 'update', 'delete', 'start', 'stop')),
    changes jsonb NOT NULL CHECK (jsonb_typeof(changes) = 'object'),
    created_at text NOT NULL
);
CREATE INDEX audit_events_guest_id ON guest_registry.audit_events(guest_id, id DESC);
CREATE TABLE guest_registry.staff (
    actor_id bigint PRIMARY KEY CHECK (actor_id > 0),
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    username text NOT NULL DEFAULT '',
    updated_at text NOT NULL
);
CREATE TABLE guest_registry.employee_access (
    user_id bigint PRIMARY KEY CHECK (user_id BETWEEN 1 AND 9007199254740991),
    added_by bigint NOT NULL CHECK (added_by BETWEEN 1 AND 9007199254740991),
    added_at text NOT NULL
);
CREATE TABLE guest_registry.visit_reminders (
    visit_id bigint NOT NULL REFERENCES guest_registry.visits(id) ON DELETE CASCADE,
    recipient_id bigint NOT NULL CHECK (recipient_id > 0),
    sent_at text NOT NULL,
    PRIMARY KEY (visit_id, recipient_id)
);
-- Residual historic totals recovered from a trustworthy card summary. Exact
-- recovered visits have already been subtracted by the recovery operator.
-- These values intentionally do not invent individual visits or their dates.
CREATE TABLE guest_registry.recovered_totals (
    guest_id bigint PRIMARY KEY REFERENCES guest_registry.guests(id) ON DELETE CASCADE,
    completed_count bigint NOT NULL CHECK (completed_count >= 0),
    completed_seconds bigint NOT NULL CHECK (completed_seconds >= 0),
    observed_at text NOT NULL,
    source_message_id text NOT NULL CHECK (length(btrim(source_message_id)) BETWEEN 1 AND 200)
);

ALTER TABLE guest_registry.registry_meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE guest_registry.guests ENABLE ROW LEVEL SECURITY;
ALTER TABLE guest_registry.visits ENABLE ROW LEVEL SECURITY;
ALTER TABLE guest_registry.audit_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE guest_registry.staff ENABLE ROW LEVEL SECURITY;
ALTER TABLE guest_registry.employee_access ENABLE ROW LEVEL SECURITY;
ALTER TABLE guest_registry.visit_reminders ENABLE ROW LEVEL SECURITY;
ALTER TABLE guest_registry.recovered_totals ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA guest_registry FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA guest_registry FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA guest_registry REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA guest_registry REVOKE ALL ON SEQUENCES FROM PUBLIC;
-- Supabase roles may not exist on an ordinary PostgreSQL server.
DO $$
DECLARE role_name text;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON SCHEMA guest_registry FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA guest_registry FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA guest_registry FROM %I', role_name);
        END IF;
    END LOOP;
END $$;
